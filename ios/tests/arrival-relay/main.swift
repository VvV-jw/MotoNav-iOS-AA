import Foundation

var checks = 0
func check(_ condition: Bool, _ message: String) {
    checks += 1
    precondition(condition, message)
}
let bridge = NaviBridge()
let manager = AMapNaviDriveManager()
let straight = LaneGuidance.encode(background: "1|0|0|4", selected: "255|0|0|0")
check(straight.packet == "#j,1f000040" && straight.count == 4, "provider straight-through lane row keeps exact lane positions")
let turn = LaneGuidance.encode(background: "1|2|0|3", selected: "1|1|255|255")
check(turn.packet == "#j,11210f3f", "left-turn recommendations do not shift across lanes")
check(LaneGuidance.encode(background: " 13 | 14 ", selected: "0|11").packet == "#j,00bb", "widening decoration preserves exact SDK directions")
for bad in ["0||3", "|0|3", "0|3|", "0|bad|3", "0|-1|3", "0|16|3", "0|255|3", "0|9999999999999999999999|3"] {
    check(LaneGuidance.encode(background: bad, selected: "0|255|3").packet == "#j", "invalid or unsupported lane row clears instead of guessing: \(bad)")
}
check(LaneGuidance.encode(background: "0|0", selected: "0").packet == "#j", "missing selection field never moves a recommendation")
check(LaneGuidance.encode(background: "0|0", selected: "0|").packet == "#j", "empty selection rejected")
check(LaneGuidance.encode(background: "0|0", selected: "0|16").packet == "#j", "unknown selected direction never becomes straight")
check(LaneGuidance.encode(background: "", selected: "").packet == "#j", "no provider lanes clears display")
check(LaneGuidance.encode(background: Array(repeating: "0", count: 9).joined(separator: "|"), selected: Array(repeating: "0", count: 9).joined(separator: "|")).packet == "#j", "unsupported lane count does not hide selected rightmost lane")
for code in 0...12 {
    let row = LaneGuidance.encode(background: "\(code)", selected: "\(code)")
    check(row.packet == "#j," + String(code, radix: 16) + String(code, radix: 16), "all legacy directions round trip")
}
check(LaneGuidance.unavailableForIndependent(bicycle: false).contains("摩托车"), "motor metadata does not claim driving lanes apply")
check(LaneGuidance.unavailableForIndependent(bicycle: true).contains("自行车"), "bicycle unavailability explicit")
let first = bridge.arrival.begin(simulation: true)
let old = NaviSessionCallbacks(bridge: bridge, token: first)
check(old.asDelegate != nil, "runtime delegate protocol registered")
check(old.asRepresentative != nil, "runtime data protocol registered")
old.mnNaviInfo(manager, info: nil)
check(bridge.calls == ["mnNaviInfo"], "current guidance delivered immediately on main")
old.mnEmuEnd(manager)
old.mnArrived(manager)
old.mnEmuEnd(manager)
old.mnNaviInfo(manager, info: nil)
old.mnLocation(manager, location: nil)
old.mnLaneShow(manager, back: "1|0", select: "1|255")
old.mnLaneHide(manager)
old.mnRouteSuccessOld(manager)
check(bridge.terminalCount == 1, "terminal callback delivered only once")
check(bridge.calls == ["mnNaviInfo", "mnEmuEnd"], "closed trip drops all subsequent SDK callbacks")
let second = bridge.arrival.begin(simulation: false)
let current = NaviSessionCallbacks(bridge: bridge, token: second)
old.mnArrived(manager)
old.mnRouteSuccessNew(manager, type: 0)
check(bridge.arrival.acceptsGuidance(second), "retained old delegate cannot finish new trip")
check(bridge.calls.count == 2, "old delegate cannot forward route success")
current.mnEmuEnd(manager)
check(bridge.terminalCount == 1 && bridge.arrival.acceptsGuidance(second), "GPS mode ignores emulator end")
bridge.arrival.cancel(second)
current.mnEmuEnd(manager) // Simulates stopNavi calling back synchronously after manual exit.
current.mnArrived(manager)
check(bridge.terminalCount == 1, "manual stop gates synchronous end callback")
let planning = bridge.arrival.preparePlan()
let queued = NaviSessionCallbacks(bridge: bridge, token: planning)
let queuedReady = DispatchSemaphore(value: 0)
DispatchQueue.global().async {
    queued.mnRouteSuccessOld(manager)
    queuedReady.signal()
}
check(queuedReady.wait(timeout: .now() + 5) == .success, "background callback queued")
let newest = bridge.arrival.begin(simulation: true)
let fresh = NaviSessionCallbacks(bridge: bridge, token: newest)
let before = bridge.calls.count
let delivered = DispatchSemaphore(value: 0)
DispatchQueue.global().async {
    fresh.mnNaviInfo(manager, info: nil)
    delivered.signal()
}
check(delivered.wait(timeout: .now() + 5) == .success, "current background callback queued")
RunLoop.main.run(until: Date().addingTimeInterval(0.1))
check(bridge.calls.count == before + 1 && bridge.calls.last == "mnNaviInfo", "main queue drops old planning result and accepts current guidance")
check(!bridge.offMain, "all forwarded callbacks execute on main queue")
check(fresh.responds(to: NSSelectorFromString("driveManager:showLaneBackInfo:laneSelectInfo:")), "actual SDK lane-show selector exposed")
check(fresh.responds(to: NSSelectorFromString("driveManagerHideLaneInfo:")), "actual SDK lane-hide selector exposed")
fresh.mnLaneShow(manager, back: "0|0", select: "0|255")
fresh.mnLaneHide(manager)
check(Array(bridge.calls.suffix(2)) == ["mnLaneShow", "mnLaneHide"], "active-session lane show and hide are relayed")
fresh.mnArrived(manager)
check(bridge.terminalCount == 2, "new trip can complete normally")
check(!fresh.mnSoundPlaying(manager), "closed delegate does not revive speech")
print("Arrival callback relay: \(checks) checks passed")
